#!/usr/bin/env python3
"""Builds OUTPUT/audit_trail/REQUIREMENT_TRACEABILITY_MATRIX.md deterministically.

Joins REQUIREMENT_REGISTER -> SUBMISSION_EVIDENCE_MAP -> PRIMARY_ASSESSMENT ->
SECOND_MARKER_REVIEW -> VERIFIED_FINDINGS for whichever of those exist, so the
matrix can be produced right after Agent 2 and refreshed at release.
"""
from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from common import AUDIT_DIR, load_json  # noqa: E402


def cell(text) -> str:
    return str(text if text not in (None, "") else "—").replace("|", "\\|").replace("\n", " ")


def build(trail: Path = AUDIT_DIR) -> Path:
    def opt(name):
        p = trail / name
        return load_json(p) if p.exists() else None

    reg = opt("REQUIREMENT_REGISTER.json")
    if reg is None:
        raise SystemExit("REQUIREMENT_REGISTER.json not found.")
    em, pa, sm = opt("SUBMISSION_EVIDENCE_MAP.json"), opt("PRIMARY_ASSESSMENT.json"), opt("SECOND_MARKER_REVIEW.json")
    links = {l["requirement_id"]: l for l in (em or {}).get("requirement_links", [])}
    assess = {a["requirement_id"]: a for a in (pa or {}).get("requirement_assessments", [])}
    second = {c["requirement_id"]: c for c in (sm or {}).get("requirement_challenges", [])}
    findings = {}
    for fname in ("PRIMARY_ASSESSMENT.json", "SPECIALIST_REVIEW.json", "EVIDENCE_AUDIT.json",
                  "COHERENCE_AUDIT.json", "SECOND_MARKER_REVIEW.json"):
        doc = opt(fname)
        for f in (doc or {}).get("findings", []):
            findings.setdefault(f["requirement_ref"], []).append(f["finding_id"])

    lines = [
        "# Requirement Traceability Matrix",
        "",
        f"Analysis mode: **{reg['analysis_mode']}** — generated by `SYSTEM/TOOLS/build_rtm.py` from the audit trail.",
        "",
        "| REQ | Obligation | Category | Requirement | Source (file / location) | Evidence location(s) | Coverage | Primary status | Second marker | Findings |",
        "|---|---|---|---|---|---|---|---|---|---|",
    ]
    for r in reg["requirements"]:
        rid = r["id"]
        link = links.get(rid, {})
        a = assess.get(rid, {})
        s = second.get(rid)
        sm_txt = "—" if not s else ("agrees" if s["agree"] else f"disagrees → {s['second_status']}")
        lines.append("| " + " | ".join(cell(x) for x in [
            rid, r["obligation"], r["category"], r["text"],
            f"{r['source']['file_id']} / {r['source']['location']}",
            ", ".join(link.get("loc_ids", [])) or a.get("evidence_location"),
            link.get("coverage"), a.get("status"), sm_txt, ", ".join(findings.get(rid, [])),
        ]) + " |")
    if reg.get("conflicts"):
        lines += ["", "## Conflicts between supplied documents", ""]
        for c in reg["conflicts"]:
            lines.append(f"- **{c['id']}** ({', '.join(c['requirement_ids'])}): {c['description']} — "
                         f"handling: {c['handling']}")
    if reg.get("not_provided"):
        lines += ["", "## Not provided by the supplied material", ""]
        lines += [f"- {x}: NOT PROVIDED" for x in reg["not_provided"]]
    out = trail / "REQUIREMENT_TRACEABILITY_MATRIX.md"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return out


if __name__ == "__main__":
    print(f"Wrote {build()}")
